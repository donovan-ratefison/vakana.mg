// Writes the offline service worker of the Expo web export.
// Usage: node scripts/build-sw.mjs [dir=dist]
// The cache name is a hash of every file path and content, so each build
// that changes a file gets a new cache.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(process.argv[2] || 'dist');
if (!existsSync(join(root, 'index.html'))) {
  console.error(`No index.html in ${root}. Run "expo export --platform web" first.`);
  process.exit(1);
}

const files = readdirSync(root, { recursive: true })
  .filter((rel) => rel !== 'sw.js' && statSync(join(root, rel)).isFile())
  .map((rel) => ({
    url: '/' + rel.split(sep).map(encodeURIComponent).join('/'),
    body: readFileSync(join(root, rel)),
  }))
  .sort((a, b) => (a.url < b.url ? -1 : 1));

const hash = createHash('sha256');
let bytes = 0;
for (const { url, body } of files) {
  // The length keeps two (path, content) pairs from hashing like one.
  hash.update(`${url}\0${body.length}\0`).update(body);
  bytes += body.length;
}
const cache = `vakana-${hash.digest('hex').slice(0, 12)}`;

const template = readFileSync(
  join(dirname(fileURLToPath(import.meta.url)), 'sw-template.js'),
  'utf8'
);
writeFileSync(
  join(root, 'sw.js'),
  '// Generated by scripts/build-sw.mjs. Do not edit.\n' +
    `const CACHE = ${JSON.stringify(cache)};\n` +
    `const FILES = ${JSON.stringify(files.map((f) => f.url), null, 1)};\n` +
    template
);
console.log(`${cache}: ${files.length} files, ${bytes} bytes`);
